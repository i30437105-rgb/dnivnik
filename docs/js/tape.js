// ---------- Генератор мини-схем ----------
// bars: [{h,l,c,up,w?}] в условных ценах (w — жирный бар); vol: числа (или null);
// levels: [{y,label?,dash?,col?}]; notes: [{i,y,text,dy?,anchor?,col?}] — подпись у бара;
// vnotes: [{i,text}] — подпись под объёмом; arrows: [{i1,y1,i2,y2,col?}]
function fig({ bars, vol = null, levels = [], notes = [], vnotes = [], arrows = [], W = 470 }) {
  const chartH = 150;
  const volH = vol ? 44 : 0;
  const H = chartH + volH + (vol ? 14 : 6);
  const padL = 12, padR = 12;
  const n = bars.length;
  const step = (W - padL - padR) / n;
  const xs = (i) => padL + (i + 0.5) * step;
  const hiAll = Math.max(...bars.map((b) => b.h), ...levels.map((l) => l.y), ...notes.map((t) => t.y));
  const loAll = Math.min(...bars.map((b) => b.l), ...levels.map((l) => l.y), ...notes.map((t) => t.y));
  const ys = (v) => 12 + ((hiAll - v) / (hiAll - loAll || 1)) * (chartH - 24);
  const vMax = vol ? Math.max(...vol) : 1;
  const vy = (v) => chartH + volH - (v / vMax) * (volH - 6);
  const tick = Math.max(3, Math.min(6, step * 0.32));
  const parts = [];

  for (const lv of levels) {
    parts.push(`<line x1="${padL}" y1="${ys(lv.y)}" x2="${W - padR}" y2="${ys(lv.y)}"
      stroke="${lv.col ?? MU}" stroke-width="1.3" ${lv.dash === false ? "" : 'stroke-dasharray="7 5"'}/>`);
    if (lv.label) parts.push(`<text x="${padL + 2}" y="${ys(lv.y) - 5}" fill="${lv.col ?? MU}" font-size="11">${lv.label}</text>`);
  }
  bars.forEach((b, i) => {
    const col = b.up ? UP : DN;
    const wd = b.w ? 3 : 1.7;
    parts.push(`<line x1="${xs(i)}" y1="${ys(b.h)}" x2="${xs(i)}" y2="${ys(b.l)}" stroke="${col}" stroke-width="${wd}"/>`);
    parts.push(`<line x1="${xs(i)}" y1="${ys(b.c)}" x2="${xs(i) + tick}" y2="${ys(b.c)}" stroke="${col}" stroke-width="${wd}"/>`);
    if (vol) parts.push(`<rect x="${xs(i) - step * 0.28}" y="${vy(vol[i])}" width="${step * 0.56}" height="${chartH + volH - vy(vol[i])}" fill="${col}" opacity=".85"/>`);
  });
  for (const a of arrows) {
    parts.push(`<line x1="${xs(a.i1)}" y1="${ys(a.y1)}" x2="${xs(a.i2)}" y2="${ys(a.y2)}"
      stroke="${a.col ?? AC}" stroke-width="1.6" marker-end="url(#tarr)"/>`);
  }
  for (const t of notes) {
    parts.push(`<text x="${xs(t.i)}" y="${ys(t.y) + (t.dy ?? -8)}" fill="${t.col ?? TX}"
      font-size="11.5" text-anchor="${t.anchor ?? "middle"}" font-weight="600">${t.text}</text>`);
  }
  for (const t of vnotes) {
    parts.push(`<text x="${xs(t.i)}" y="${chartH + volH + 12}" fill="${AC}" font-size="11" text-anchor="middle" font-weight="600">${t.text}</text>`);
  }
  return `<svg viewBox="0 0 ${W} ${H}" role="img" style="display:block;width:100%;max-width:${W + 40}px;height:auto;
    background:var(--bg-inset);border:1px solid var(--chart-grid);border-radius:10px;margin:10px 0 4px">
    <defs><marker id="tarr" markerWidth="8" markerHeight="8" refX="6" refY="3" orient="auto">
      <path d="M0,0 L7,3 L0,6 z" fill="${AC}"/></marker></defs>${parts.join("")}</svg>`;
}

